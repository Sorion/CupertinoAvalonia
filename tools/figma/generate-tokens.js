// Generate the theme's token dictionaries from the values extracted from Apple's kit.
// Usage: node generate-tokens.js <extractedDir> <tokensOutDir>
// Output files are *.g.axaml: never edit them by hand, change this script and rerun `npm run tokens`.
const fs = require('fs');
const path = require('path');
const [, , extractedDir, outDir] = process.argv;

const variables = JSON.parse(fs.readFileSync(path.join(extractedDir, 'variables.json')));
const styles = JSON.parse(fs.readFileSync(path.join(extractedDir, 'styles.json')));
const collection = (name) => Object.entries(variables).find(([k, v]) => k.startsWith(name + ' (') && Object.keys(v.variables).length)[1];

const header = (what) => `<!--
  GENERATED by tools/figma/generate-tokens.js from Apple's macOS 27 Figma kit (${what}).
  Do not edit by hand: change the generator and run \`npm run tokens\` in tools/figma.
-->
<ResourceDictionary xmlns="https://github.com/avaloniaui"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
`;
const pascal = (s) => s.replace(/\([^)]*\)/g, ' ').split(/[^A-Za-z0-9]+/).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join('');
const valueOf = (x) => (x && typeof x === 'object' && 'value' in x ? x.value : x);
const write = (file, body) => fs.writeFileSync(path.join(outDir, file), body);

// ---------- Colors ----------
const colorNames = {
  'Labels/Seximal': null,
  'Controls/Tint': null,
  'Mode': null,
  'String': null,
  'Grays/Black': 'BlackColor',
  'Grays/White': 'WhiteColor',
  'Grays/Gray': 'GrayColor',
  'Glyphs/Primary - Idle': 'GlyphPrimaryColor',
  'Glyphs/Primary - Disabled': 'GlyphPrimaryDisabledColor',
  'Window Background': 'WindowBackgroundColor',
  'Material/Ultra Thick': null, // emitted with the other materials below
  'Material/Thin': null,
  'Miscellaneous/Tooltips/Inner Stroke': 'TooltipInnerStrokeColor',
  'Miscellaneous/Alerts/Overlay': 'AlertOverlayColor',
  'Miscellaneous/Scrollbar': 'ScrollBarThumbColor',
  'Miscellaneous/Progress Bars/Track - Stroke': 'ProgressTrackStrokeColor',
  'Miscellaneous/Tables/BG - Selected + Inactive': 'TableRowSelectedInactiveColor',
  'Miscellaneous/Tables/Alternating Row Color': 'TableRowAlternateColor',
  'Miscellaneous/Tables/BG - Selected + Active': 'TableRowSelectedColor',
  'Miscellaneous/Tables/Column Separator': 'TableColumnSeparatorColor',
  'Miscellaneous/Tooltips/Sidebar - BG - Active': 'SidebarBackgroundColor',
  'Miscellaneous/Tooltips/Sidebar - BG - Inactive': 'SidebarBackgroundInactiveColor',
  'Miscellaneous/Sidebar/Label - Inactive': 'SidebarLabelInactiveColor',
};
const groupNames = { 'Accents': 'Accent', 'Accents - Vibrant': 'AccentVibrant', 'Fills - Opaque': 'Fill', 'Fills - Vibrant': 'FillVibrant', 'Labels': 'Label', 'Labels - Vibrant': 'LabelVibrant' };
function colorKey(name) {
  if (name in colorNames) return colorNames[name];
  if (name.startsWith('❌')) return null;
  const [group, leaf] = name.split('/');
  const g = groupNames[group.replace(/\s*\(.*\)\s*/, '').trim()];
  if (!g || !leaf) throw new Error('No resource name for color variable: ' + name);
  return g + pascal(leaf) + 'Color';
}

// Materials: the kit mixes variables and fill styles, and swaps Light/Dark for Menu and Popover.
const fillStyle = (name) => {
  const s = styles.find((x) => x.type === 'FILL' && x.name === name);
  if (!s) throw new Error('Missing fill style ' + name);
  return s.fills[s.fills.length - 1].c; // last = topmost, solid part of the material
};
const colorsVars = collection('Colors').variables;
const materials = {
  MaterialUltraThickColor: [colorsVars['Material/Ultra Thick'].Light, colorsVars['Material/Ultra Thick'].Dark],
  MaterialThickColor: [fillStyle('Materials/Thick'), fillStyle('Materials/Thick - Dark')],
  MaterialMediumColor: [fillStyle('Materials/Medium'), fillStyle('Materials/Medium - Dark')],
  MaterialThinColor: [colorsVars['Material/Thin'].Light, colorsVars['Material/Thin'].Dark],
  MaterialUltraThinColor: [fillStyle('Materials/Ultrathin'), fillStyle('Materials/Ultrathin - Dark')],
  MaterialSidebarColor: [fillStyle('Materials - Controls/Sidebar'), fillStyle('Materials - Controls/Sidebar - Dark')],
  MaterialTitleBarColor: [fillStyle('Materials - Controls/Title Bar'), fillStyle('Materials - Controls/Title Bar - Dark')],
  MaterialHeaderViewColor: [fillStyle('Materials - Controls/Header View'), styles.find((x) => x.name === 'Materials - Controls/Header View - Dark').fills[0].c],
  MaterialMenuColor: [fillStyle('Materials - Controls/Menu - Dark'), fillStyle('Materials - Controls/Menu')],
  MaterialPopoverColor: [fillStyle('Materials - Controls/Popover - Dark'), fillStyle('Materials - Controls/Popover')],
  MaterialUnderWindowBackgroundColor: [fillStyle('Materials - Controls/Under Window Background'), fillStyle('Materials - Controls/Under Window Background - Dark')],
};

{
  const rows = { Default: [], Dark: [] };
  for (const [name, row] of Object.entries(colorsVars)) {
    const key = colorKey(name);
    if (!key) continue;
    rows.Default.push([key, valueOf(row.Light)]);
    rows.Dark.push([key, valueOf(row.Dark)]);
  }
  for (const [key, [light, dark]] of Object.entries(materials)) {
    rows.Default.push([key, light]);
    rows.Dark.push([key, dark]);
  }
  // Avalonia has no blend modes: the vibrant fills and labels as the translucent colors they amount to, black under
  // a linear burn in light mode, white under a linear dodge in dark mode (FillVibrantSecondary #E6E6E6 → #1A000000).
  const h2 = (n) => n.toString(16).padStart(2, '0').toUpperCase();
  for (const variant of ['Default', 'Dark']) {
    for (const [key, value] of [...rows[variant]]) {
      if (!/^(Fill|Label)Vibrant/.test(key)) continue;
      const gray = /^#([0-9A-F]{2})\1\1$/i.exec(value);
      if (!gray) throw new Error(`${key} isn't an opaque gray: ${value}`);
      const level = parseInt(gray[1], 16);
      rows[variant].push([key.replace(/Color$/, 'TranslucentColor'), variant === 'Dark' ? `#${h2(level)}FFFFFF` : `#${h2(255 - level)}000000`]);
    }
  }
  const dict = (variant) => rows[variant].map(([k, v]) => `      <Color x:Key="${k}">${v}</Color>`).join('\n') + '\n\n' +
    rows[variant].map(([k]) => `      <SolidColorBrush x:Key="${k.replace(/Color$/, 'Brush')}" Color="{StaticResource ${k}}" />`).join('\n');
  write('Colors.g.axaml', header('Colors and Materials') + `  <ResourceDictionary.ThemeDictionaries>
    <ResourceDictionary x:Key="Default">
${dict('Default')}
    </ResourceDictionary>
    <ResourceDictionary x:Key="Dark">
${dict('Dark')}
    </ResourceDictionary>
  </ResourceDictionary.ThemeDictionaries>
</ResourceDictionary>
`);
}

// ---------- Metrics (control sizes) ----------
const sizeSuffix = { Mini: 'Mini', Small: 'Small', Medium: '', Large: 'Large', XL: 'XLarge' };
const sizeGroups = { 'Global': 'Control', 'Toggle (Switch)': 'Switch', 'Radio Button': 'RadioButton', 'Checkboxes': 'CheckBox', 'Fields': 'TextField', 'Segmented Control': 'SegmentedControl', 'Combo Button': 'ComboBox', 'Arrow Button': 'ArrowButton', 'Color Well': 'ColorWell', 'Popup': 'PopUpButton' };
// Measured on macOS 27 where the kit differs: what AppKit and SwiftUI draw wins. Marked in the output.
const measured = {
  // NSFont.systemFontSize(for: .mini): every mini control's text, in AppKit and SwiftUI.
  'Global/Font Size': { Mini: 9 },
  // A push button sized to fit is its label plus this on each side (NSButton, SwiftUI's Button).
  'Button/Padding - Horizontal': { Mini: 8, Medium: 12, Large: 14, XL: 18 },
  // NSPopUpButton's label inset.
  'Popup/Inset - Left': { Mini: 8 },
};
{
  const sizes = collection('Sizes');
  const lines = [];
  const byName = {};
  for (const [name, row] of Object.entries(sizes.variables)) {
    if (name === 'Mode') continue;
    const [group, ...rest] = name.split('/');
    const base = (sizeGroups[group] ?? pascal(group)) + pascal(rest.join(' '));
    byName[name] = {};
    for (const mode of sizes.modes) {
      const kit = Math.round(valueOf(row[mode]) * 100) / 100;
      const v = measured[name]?.[mode] ?? kit;
      byName[name][mode] = v;
      const key = base + sizeSuffix[mode];
      const note = v !== kit ? ` <!-- macOS 27; the kit's ${kit} -->` : '';
      lines.push((/Radius/.test(name) ? `  <CornerRadius x:Key="${key}">${v}</CornerRadius>` : `  <x:Double x:Key="${key}">${v}</x:Double>`) + note);
    }
  }
  for (const name of Object.keys(measured)) if (!byName[name]) throw new Error(`No kit variable ${name}`);
  // Thickness resources can't be composed from doubles in XAML: generate them here.
  const composites = [
    ['ButtonPadding', (m) => `${byName['Button/Padding - Horizontal'][m]},0`],
    ['TextFieldPadding', (m) => `${byName['Fields/Inset - Left'][m]},0,${byName['Fields/Inset - Right'][m]},0`],
    ['PopUpButtonPadding', (m) => `${byName['Popup/Inset - Left'][m]},0,0,0`],
    ['SegmentedControlPadding', (m) => `${byName['Segmented Control/Margins'][m]},0`],
  ];
  for (const [key, f] of composites) for (const mode of sizes.modes) lines.push(`  <Thickness x:Key="${key}${sizeSuffix[mode]}">${f(mode)}</Thickness>`);
  // Values derived from several variables.
  const derived = [
    // How far the switch knob travels: ToggleSwitch moves PART_MovingKnobs from 0 to PART_SwitchKnob's width.
    ['SwitchKnobTravel', (m) => byName['Toggle (Switch)/Track - Width'][m] - byName['Toggle (Switch)/Knob - Width'][m] - 2 * byName['Toggle (Switch)/Knob - Inset'][m]],
  ];
  for (const [key, f] of derived) for (const mode of sizes.modes) lines.push(`  <x:Double x:Key="${key}${sizeSuffix[mode]}">${Math.round(f(mode) * 100) / 100}</x:Double>`);
  for (const mode of sizes.modes) lines.push(`  <Thickness x:Key="SwitchKnobMargin${sizeSuffix[mode]}">${byName['Toggle (Switch)/Knob - Inset'][mode]},0,0,0</Thickness>`);
  write('Metrics.g.axaml', header('Sizes collection: Mini, Small, Medium, Large, XL') + `  <!-- Medium is macOS's regular control size and has no suffix. Values marked "macOS 27" were measured on it and replace\n       the kit's (see \`measured\` in the generator). -->\n` + lines.join('\n') + '\n</ResourceDictionary>\n');
}

// ---------- Typography ----------
{
  // SF's Heavy is 800, Avalonia's ExtraBold: Avalonia's Heavy is 900, SF's Black.
  const weight = (font) => ({ Regular: 'Regular', Medium: 'Medium', Semibold: 'SemiBold', Bold: 'Bold', Heavy: 'ExtraBold' })[font.split(' ').slice(-1)[0]];
  const lines = [];
  for (const s of styles.filter((x) => x.type === 'TEXT')) {
    const m = s.name.match(/^(.+)\/(Regular|Emphasized)$/);
    if (!m) continue;
    const base = pascal(m[1]);
    if (m[2] === 'Regular') {
      lines.push(`  <x:Double x:Key="${base}FontSize">${s.size}</x:Double>`);
      lines.push(`  <x:Double x:Key="${base}LineHeight">${parseFloat(s.lh)}</x:Double>`);
      lines.push(`  <FontWeight x:Key="${base}FontWeight">${weight(s.font)}</FontWeight>`);
    } else {
      lines.push(`  <FontWeight x:Key="${base}EmphasizedFontWeight">${weight(s.font)}</FontWeight>`);
    }
  }
  write('Typography.g.axaml', header('Text Styles') + lines.join('\n') + '\n</ResourceDictionary>\n');
}

// ---------- Shadows ----------
{
  const shadow = (s) => s.effects.filter((e) => e.t === 'DROP_SHADOW' || e.t === 'INNER_SHADOW').map((e) => `${e.t === 'INNER_SHADOW' ? 'inset ' : ''}${e.o[0]} ${e.o[1]} ${e.r} ${e.s ?? 0} ${e.c}`).join(', ');
  const variant = (prefix) => styles.filter((x) => x.type === 'EFFECT' && x.name.startsWith(prefix)).map((s) => `      <BoxShadows x:Key="${pascal('Shadow ' + s.name.slice(prefix.length).replace(/^WIndow/, 'Window'))}">${shadow(s)}</BoxShadows>`).join('\n');
  write('Shadows.g.axaml', header('Effect Styles') + `  <ResourceDictionary.ThemeDictionaries>
    <ResourceDictionary x:Key="Default">
${variant('Shadows - Light/')}
    </ResourceDictionary>
    <ResourceDictionary x:Key="Dark">
${variant('Shadows - Dark/')}
    </ResourceDictionary>
  </ResourceDictionary.ThemeDictionaries>
</ResourceDictionary>
`);
}
console.log('tokens written to ' + outDir);
